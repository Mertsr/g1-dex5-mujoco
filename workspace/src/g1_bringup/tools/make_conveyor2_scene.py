#!/usr/bin/env python3
"""Generate g1_conveyor2_scene.xml: the conveyor world with a stand-in part.

world:=conveyor2 is g1_conveyor_scene.xml exactly -- tray, conveyor, pallet, robot, everything --
except that every BSH panel (part_tray_1..4 and part_drop_test) is replaced by an upright
cylinder. It exists to build and exercise the pick-and-place system (tracking, Pick, Place into
a nest) with a part the hand can certainly hold, while the real panel's grasp waits for the real
hand. The bodies keep their names, so everything that looks them up still finds them.

The cylinder, in its body frame (world-aligned, axis along z):
  RADIUS 22.5 mm (45 mm across: inside the RH56E2's ~58 mm thumb-to-index opening, with room for
         a top-down pinch to close on it), HEIGHT 104.6 mm, 0.15 kg
  origin at its centre, which is what Pick's bounding-box grasp assumes (it aims HEIGHT/2 above
         the reported pose for the top face)

HEIGHT is chosen so that a cylinder standing on the pallet plate (pallet z +0.01) at a nest's
centre -- between that nest's end cradles, which are 0.51 m apart -- has its origin at pallet
z 0.0623, inside the nest site the simulator's conveyor handler watches. A placed cylinder
therefore fills the nest and the pallet indexes, exactly as for a seated panel.

Also writes the tracker's model of the same part (g1_perception/models/cylinder.stl, in this
body frame, metres) so the depth tracker and the simulator agree on the shape exactly.

    make_conveyor2_scene.py                 # default paths
"""

import argparse
import pathlib
import re
import struct

import numpy as np

RADIUS = 0.0225
HEIGHT = 0.1046
MASS = 0.15
SEGMENTS = 48  # around the tracker model's circumference

# Where the four tray parts stand (x as the panels in g1_conveyor_scene.xml, between the tray's
# low stop bars; on the tray floor, top z 0.71) and where the drop-test part starts (above the
# load station's nest, its bottom 10 mm above the tallest cradle wall, z 0.842, so it falls onto
# the plate between the cradles when the simulation starts).
TRAY_FLOOR = 0.71
TRAY_X = {1: 1.605, 2: 1.755, 3: 1.905, 4: 2.055}
TRAY_Y = -0.80
DROP_POS = (0.40, 0.60, 0.842 + 0.010 + HEIGHT / 2)


def _fmt(v):
    return " ".join(f"{x:.5g}" for x in v)


def body_xml(name, pos):
    return (
        f'    <body name="{name}" pos="{_fmt(pos)}">\n'
        f'      <joint type="free" name="{name}_joint" damping="0.2"/>\n'
        f'      <geom name="{name}_cylinder" group="2" type="cylinder" '
        f'size="{RADIUS:.5g} {HEIGHT / 2:.5g}" material="mat_part" mass="{MASS:.4g}" '
        f'contype="1" conaffinity="1" friction="1 0.01 0.0001"/>\n'
        "    </body>"
    )


def write_stl(path):
    a = np.linspace(0.0, 2 * np.pi, SEGMENTS, endpoint=False)
    ring = np.c_[RADIUS * np.cos(a), RADIUS * np.sin(a)]
    top, bot = HEIGHT / 2, -HEIGHT / 2
    tris = []
    for i in range(SEGMENTS):
        j = (i + 1) % SEGMENTS
        p0b, p1b = np.r_[ring[i], bot], np.r_[ring[j], bot]
        p0t, p1t = np.r_[ring[i], top], np.r_[ring[j], top]
        tris += [(p0b, p1b, p1t), (p0b, p1t, p0t)]  # side, outward
        tris.append((np.array([0.0, 0.0, top]), p0t, p1t))  # top cap, +z
        tris.append((np.array([0.0, 0.0, bot]), p1b, p0b))  # bottom cap, -z
    with open(path, "wb") as fh:
        fh.write(b"cylinder (make_conveyor2_scene.py)".ljust(80, b" "))
        fh.write(struct.pack("<I", len(tris)))
        for t in tris:
            n = np.cross(t[1] - t[0], t[2] - t[0])
            n = n / np.linalg.norm(n)
            fh.write(struct.pack("<12fH", *n, *t[0], *t[1], *t[2], 0))


def main():
    here = pathlib.Path(__file__).resolve().parent
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument(
        "--src", type=pathlib.Path, default=here.parent / "mjcf" / "g1_conveyor_scene.xml"
    )
    p.add_argument(
        "--dst", type=pathlib.Path, default=here.parent / "mjcf" / "g1_conveyor2_scene.xml"
    )
    p.add_argument(
        "--stl",
        type=pathlib.Path,
        default=here.parents[1] / "g1_perception" / "models" / "cylinder.stl",
    )
    a = p.parse_args()
    s = a.src.read_text()
    bodies = {f"part_tray_{k}": (x, TRAY_Y, TRAY_FLOOR + HEIGHT / 2) for k, x in TRAY_X.items()}
    bodies["part_drop_test"] = DROP_POS
    for name, pos in bodies.items():
        m = re.search(rf'    <body name="{name}"[^>]*>.*?\n    </body>', s, re.S)
        if not m:
            raise SystemExit(f"{a.src}: no body {name}")
        s = s[: m.start()] + body_xml(name, pos) + s[m.end() :]
    note = (
        "<!-- GENERATED by g1_bringup/tools/make_conveyor2_scene.py from g1_conveyor_scene.xml:\n"
        "     the same world with every BSH panel replaced by an upright cylinder (see that tool).\n"
        "     Do not edit by hand; edit g1_conveyor_scene.xml or the tool and regenerate. -->\n"
    )
    s = s.replace('<mujoco model="g1_conveyor_scene">', '<mujoco model="g1_conveyor2_scene">', 1)
    s = re.sub(r"(<mujoco[^>]*>\n)", r"\1" + note, s, count=1)
    a.dst.write_text(s)
    write_stl(a.stl)
    print(f"wrote {a.dst} and {a.stl}")


if __name__ == "__main__":
    main()

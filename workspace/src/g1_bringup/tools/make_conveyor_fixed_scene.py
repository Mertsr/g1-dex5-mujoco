#!/usr/bin/env python3
"""Generate g1_conveyor_fixed_scene.xml from g1_conveyor_flat_scene.xml.

    python3 make_conveyor_fixed_scene.py            # from this package's mjcf/

conveyor_flat exactly, plus a grasp weld between each hand's palm and each panel: when a hand
closes on a panel, the simulator's grasp_weld manager freezes the panel where it sits in that
hand, and lets go when the hand opens. SIMULATION ONLY -- it stands in for what the real RH56E2
does by friction (a firm grip the simulated fingers do not reproduce: the panel rolled up to
40 degrees in the hand, or was pulled out by the second hand), so a pick that holds here says
the arms and the planning work, not that the fingers grip.

The settings ride in the scene (MJCF <custom><numeric>), so only this world changes; every
other world keeps grasp_weld's sim_sensors.yaml settings:

  grasp_weld_require_contact  1     the hand's collision geometry must be touching the panel --
                                    a hand closing beside it takes nothing
  grasp_weld_capture_radius   0.45  palm origin to panel origin; the panel is 0.6 m long and is
                                    held 0.1-0.35 m from its middle
  grasp_weld_close_fraction   0.35  a scoop closed on a panel measures ~0.5 (fingers stopped by
                                    the panel), the open scoop 0.06
  grasp_weld_release_fraction 0.2
  grasp_weld_second_timeconst 0.1   a hand closing on a panel the other hand already holds gets
                                    a soft weld (MuJoCo solref time constant, s; default 0.02):
                                    two rigid welds would lock the arms into one closed chain
                                    and their tracking errors would fight
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent / "mjcf"
SRC = HERE / "g1_conveyor_flat_scene.xml"
DST = HERE / "g1_conveyor_fixed_scene.xml"
PANELS = [f"part_tray_{k}" for k in range(1, 5)] + ["part_drop_test"]
SETTINGS = {
    "grasp_weld_require_contact": 1,
    "grasp_weld_capture_radius": 0.45,
    "grasp_weld_close_fraction": 0.35,
    "grasp_weld_release_fraction": 0.2,
    "grasp_weld_second_timeconst": 0.1,
}


def main():
    src = SRC.read_text()
    if "<equality>" in src or "<custom>" in src:
        sys.exit(f"{SRC.name} already has <equality> or <custom>; extend this tool to merge")
    for body in PANELS:
        if f'name="{body}"' not in src:
            sys.exit(f"{SRC.name} has no body {body}")
    src = src.replace('<mujoco model="g1_conveyor_flat_scene">', '<mujoco model="g1_conveyor_fixed_scene">', 1)
    src = src.replace(
        "<!-- GENERATED by g1_bringup/tools/make_conveyor_flat_scene.py",
        "<!-- GENERATED by g1_bringup/tools/make_conveyor_fixed_scene.py from "
        "g1_conveyor_flat_scene.xml, which is itself\n     GENERATED by "
        "g1_bringup/tools/make_conveyor_flat_scene.py",
        1,
    )
    custom = "\n".join(f'    <numeric name="{k}" data="{v}"/>' for k, v in SETTINGS.items())
    welds = "\n".join(
        f'    <weld name="grasp_{side}_{body}" body1="{side}_hand_palm_link" body2="{body}" active="false"/>'
        for body in PANELS
        for side in ("right", "left")
    )
    tail = (
        "  <!-- conveyor_fixed: grasp welds for the panels. See tools/make_conveyor_fixed_scene.py. -->\n"
        f"  <custom>\n{custom}\n  </custom>\n"
        "  <equality>\n"
        "    <!-- Inactive; only grove-g1's grasp_weld manager turns one on. SIMULATION ONLY. -->\n"
        f"{welds}\n"
        "  </equality>\n"
        "</mujoco>"
    )
    src, n = re.subn(r"</mujoco>\s*$", tail, src)
    if n != 1:
        sys.exit("could not find the closing </mujoco>")
    DST.write_text(src + "\n")
    print(f"wrote {DST} ({len(PANELS) * 2} welds)")


if __name__ == "__main__":
    main()
